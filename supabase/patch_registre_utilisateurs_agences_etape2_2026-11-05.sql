-- ── 6. poser des valeurs de Hektor sur une ligne, champ par champ ──
-- « Hektor complète, il n'écrase pas » : une valeur vide n'efface rien ; un champ du carnet n'est jamais écrit (un écart
-- se signale, une fois par valeur) ; une première valeur = « pose », un changement = « changement » (avant / après).
create or replace function public.app_registre_poser(p_objet text, p_id bigint, p_src jsonb, p_nuit date)
returns integer language plpgsql security definer set search_path to 'public' as $f$
declare
    v_table text := case p_objet when 'societe' then 'app_registre_societe' when 'agence' then 'app_registre_agence'
                                 when 'personne' then 'app_negociateur_personne' end;
    v_idcol text := case p_objet when 'societe' then 'app_societe_id' when 'agence' then 'app_agence_id'
                                 when 'personne' then 'app_personne_id' end;
    v_row jsonb; k text; v_new text; v_old text; v_carnet text; v_type text; n integer := 0;
begin
    if v_table is null then raise exception 'objet inconnu : %', p_objet; end if;
    execute format('select to_jsonb(t) from %I t where %I = $1', v_table, v_idcol) into v_row using p_id;
    if v_row is null then return 0; end if;
    for k, v_new in select key, nullif(trim(value), '') from jsonb_each_text(coalesce(p_src, '{}'::jsonb)) loop
        if v_new is null then continue; end if;
        if not (v_row ? k) then raise exception 'champ inconnu % pour %', k, p_objet; end if;
        select c.valeur into v_carnet from app_registre_champ_app c where c.objet = p_objet and c.objet_id = p_id and c.champ = k;
        if found then
            if v_carnet is distinct from v_new and not exists (
                   select 1 from app_registre_journal j where j.objet = p_objet and j.objet_id = p_id and j.champ = k
                      and j.evenement = 'ecart' and j.apres = v_new and j.traite_le is null) then
                insert into app_registre_journal (objet, objet_id, evenement, champ, avant, apres, a_signaler, nuit)
                values (p_objet, p_id, 'ecart', k, v_carnet, v_new, true, p_nuit);
            end if;
            continue;
        end if;
        v_old := v_row ->> k;
        if v_old is distinct from v_new then
            select format_type(a.atttypid, a.atttypmod) into v_type
              from pg_attribute a where a.attrelid = v_table::regclass and a.attname = k and not a.attisdropped;
            execute format('update %I set %I = $1::%s, updated_at = now() where %I = $2', v_table, k, v_type, v_idcol)
              using v_new, p_id;
            insert into app_registre_journal (objet, objet_id, evenement, champ, avant, apres, nuit)
            values (p_objet, p_id, case when v_old is null then 'pose' else 'changement' end, k, v_old, v_new, p_nuit);
            n := n + 1;
        end if;
    end loop;
    return n;
end
$f$;
revoke all on function public.app_registre_poser(text, bigint, jsonb, date) from public, anon, authenticated;
grant execute on function public.app_registre_poser(text, bigint, jsonb, date) to service_role;

-- ── 7. la tenue de nuit ──
create or replace function public.app_registre_utilisateurs_agences_maintenir(p_agences jsonb, p_negos jsonb, p_a_blanc boolean default true)
returns jsonb language plpgsql security definer set search_path to 'public' as $f$
declare
    v_nuit date := current_date;
    v_rapport jsonb;
    r record; a jsonb; j jsonb; c jsonb; v_raw jsonb;
    v_id bigint; v_nego text; v_email_app text; v_email_hektor text; v_agence bigint;
    v_agences_nouvelles int := 0; v_agences_champs int := 0; v_agences_absentes int := 0; v_alias int := 0;
    v_societe_champs int := 0; v_personnes int := 0; v_personnes_champs int := 0; v_ecarts_email int := 0;
    v_presentes int; v_lues int;
begin
    if p_agences is null or jsonb_typeof(p_agences) <> 'array' or jsonb_array_length(p_agences) = 0 then
        raise exception 'ARRET : la liste des agences est vide';
    end if;
    if p_negos is null or jsonb_typeof(p_negos) <> 'array' then
        raise exception 'ARRET : la liste des négociateurs n''est pas une liste';
    end if;
    begin
        -- A. les agences : numérotées dans l'ordre du nom, le compte formation et l'agence « supprimée » en dernier
        for a in
            select x from jsonb_array_elements(p_agences) x
             order by (case when x ->> 'id' = '1' or x ->> 'nom' ilike 'agences supprim%' then 1 else 0 end),
                      app_neg_cle_agence(x ->> 'nom'), x ->> 'id'
        loop
            continue when coalesce(trim(a ->> 'id'), '') = '';
            select g.app_agence_id into v_id from app_registre_agence g where g.hektor_agence_id = a ->> 'id';
            if not found then
                insert into app_registre_agence (nom, statut, hektor_agence_id)
                values (coalesce(nullif(trim(a ->> 'nom'), ''), 'Agence ' || (a ->> 'id')),
                        case when a ->> 'id' = '1' then 'formation' when a ->> 'nom' ilike 'agences supprim%' then 'supprimee' else 'active' end,
                        a ->> 'id')
                returning app_agence_id into v_id;
                insert into app_registre_journal (objet, objet_id, evenement, apres, nuit)
                values ('agence', v_id, 'nouvelle', a ->> 'nom', v_nuit);
                v_agences_nouvelles := v_agences_nouvelles + 1;
            elsif exists (select 1 from app_registre_agence g where g.app_agence_id = v_id and not g.present_chez_hektor) then
                insert into app_registre_journal (objet, objet_id, evenement, nuit) values ('agence', v_id, 'reapparue', v_nuit);
            end if;
            update app_registre_agence set present_chez_hektor = true, absent_depuis = null, derniere_vue = now()
             where app_agence_id = v_id;
            v_agences_champs := v_agences_champs + app_registre_poser('agence', v_id, jsonb_build_object(
                'nom', a ->> 'nom', 'email', a ->> 'mail', 'telephone', a ->> 'tel', 'fax', a ->> 'fax', 'site', a ->> 'site',
                'responsable', a ->> 'responsable', 'hektor_compte_id', a ->> 'idUser', 'logo_url', a ->> 'logo',
                'avatar_url', a ->> 'avatar', 'bareme_url', a ->> 'bareme', 'couleur', a ->> 'color',
                'siret_etablissement', a #>> '{informationJuridique,siret}'), v_nuit);
            insert into app_registre_agence_alias (cle, app_agence_id, ecriture, origine)
            select app_neg_cle_agence(e), v_id, e, 'hektor'
              from (select distinct trim(e) e from unnest(array[a ->> 'nom', a ->> 'alias']) e where coalesce(trim(e), '') <> '') s
             where app_neg_cle_agence(e) <> ''
            on conflict (cle) do nothing;
            get diagnostics v_lues = row_count;
            v_alias := v_alias + v_lues;
        end loop;
        -- absences : seulement si la liste de la nuit couvre au moins 90 % des agences présentes (plancher)
        select count(*) into v_presentes from app_registre_agence where present_chez_hektor;
        select count(*) into v_lues from jsonb_array_elements(p_agences);
        if v_lues >= ceil(0.9 * v_presentes) then
            for r in select g.app_agence_id from app_registre_agence g
                      where g.present_chez_hektor
                        and g.hektor_agence_id not in (select x ->> 'id' from jsonb_array_elements(p_agences) x where x ->> 'id' is not null)
            loop
                update app_registre_agence set present_chez_hektor = false, absent_depuis = now() where app_agence_id = r.app_agence_id;
                insert into app_registre_journal (objet, objet_id, evenement, nuit) values ('agence', r.app_agence_id, 'disparue', v_nuit);
                v_agences_absentes := v_agences_absentes + 1;
            end loop;
        end if;

        -- B. la société : la fiche d'agence dont le juridique est le plus rempli
        select x into a from jsonb_array_elements(p_agences) x
         order by (select count(*) from jsonb_each_text(coalesce(x -> 'informationJuridique', '{}'::jsonb)) e
                    where coalesce(nullif(trim(e.value), ''), '0') <> '0') desc, x ->> 'id'
         limit 1;
        j := coalesce(a -> 'informationJuridique', '{}'::jsonb);
        c := coalesce(a -> 'carteProfessionnelle', '{}'::jsonb);
        insert into app_registre_societe (app_societe_id) values (3000001) on conflict do nothing;
        v_societe_champs := app_registre_poser('societe', 3000001, jsonb_build_object(
            'raison_sociale', j ->> 'name', 'forme', coalesce(j ->> 'statut_juridique', j ->> 'type_entreprise'),
            'siret', j ->> 'siret', 'naf', j ->> 'naf', 'capital', nullif(j ->> 'capital', '0'), 'rcs', j ->> 'rcs',
            'rcs_ville', j ->> 'villeInscriptionRCS', 'tva', j ->> 'numero_tva', 'rsac', j ->> 'rsac',
            'siege_adresse', j ->> 'adresseSiegeSocial', 'siege_code_postal', j ->> 'codePostalSiegeSocial', 'siege_ville', j ->> 'villeSiegeSocial',
            'telephone', j ->> 'contact_company_phone', 'email', j ->> 'contact_company_mail',
            'rcp_numero', j ->> 'numero_rcp', 'assureur_nom', j ->> 'nomAssureur', 'assureur_adresse', j ->> 'adresseAssureur',
            'assureur_code_postal', j ->> 'codePostalAssureur', 'assureur_ville', j ->> 'villeAssureur',
            'mediateur_nom', j ->> 'nomMediateur', 'mediateur_adresse', j ->> 'adresseMediateur',
            'mediateur_code_postal', j ->> 'codePostalMediateur', 'mediateur_ville', j ->> 'villeMediateur', 'mediateur_site', j ->> 'adresseSiteMediateur',
            'carte_type', c ->> 'card_type', 'carte_numero', c ->> 'num_card', 'carte_delivree_par', c ->> 'delivered_name',
            'carte_validite', nullif(c ->> 'date', '0000-00-00'), 'carte_detenteur', c ->> 'detenteur', 'carte_maniement_fonds', c ->> 'maniements',
            'carte_garant', c ->> 'garant', 'carte_montant', nullif(c ->> 'montant', '0'),
            'bareme_url', a ->> 'bareme', 'logo_url', a ->> 'logo',
            'hektor_agence_id', a ->> 'id', 'hektor_juridique_id', j ->> 'id'), v_nuit);

        -- C. les personnes : leurs coordonnées depuis leur meilleure fiche (active d'abord, la plus récente ensuite)
        for r in select p.app_personne_id, p.app_user_id from app_negociateur_personne p where p.type_personne <> 'agence' loop
            v_personnes := v_personnes + 1;
            select f.hektor_negociateur_id into v_nego from app_negociateur_fiche f
             where f.app_personne_id = r.app_personne_id and f.sorte = 'fiche_negociateur'
             order by f.actif_chez_hektor desc, f.derniere_vue desc nulls last, f.hektor_negociateur_id desc
             limit 1;
            v_raw := null;
            if v_nego is not null then
                select x into v_raw from jsonb_array_elements(p_negos) x where x ->> 'id' = v_nego limit 1;
            end if;
            v_email_app := null;
            if r.app_user_id is not null then
                select lower(u.email) into v_email_app from auth.users u where u.id = r.app_user_id and lower(u.email) like '%@gti-immobilier.fr';
            end if;
            if v_raw is not null then
                v_email_hektor := nullif(lower(trim(v_raw ->> 'email')), '');
                select g.app_agence_id into v_agence from app_registre_agence g where g.hektor_agence_id = v_raw ->> 'agence';
                v_personnes_champs := v_personnes_champs + app_registre_poser('personne', r.app_personne_id, jsonb_build_object(
                    'prenom', v_raw ->> 'prenom', 'nom_famille', v_raw ->> 'nom',
                    'fonction', case when (v_raw ->> 'fonction') ~ '^\s*\d*\s*$' then null else v_raw ->> 'fonction' end,
                    'telephone', v_raw ->> 'telephone', 'portable', v_raw ->> 'portable',
                    'email_pro', coalesce(v_email_app, case when app_neg_email_partage(v_email_hektor) then null else v_email_hektor end),
                    'photo_url', case when (v_raw ->> 'avatar') ilike '%/nego.jpg' then null else v_raw ->> 'avatar' end,
                    'app_agence_id', v_agence::text), v_nuit);
            else
                -- sans fiche de négociateur (un compte seul) : ce que porte sa fiche de compte
                select nullif(lower(trim(f.email_vu)), '') into v_email_hektor from app_negociateur_fiche f
                 where f.app_personne_id = r.app_personne_id order by f.present_chez_hektor desc, f.derniere_vue desc nulls last limit 1;
                v_personnes_champs := v_personnes_champs + app_registre_poser('personne', r.app_personne_id, (
                    select jsonb_build_object('telephone', f.telephone, 'portable', f.portable,
                               'email_pro', coalesce(v_email_app, case when app_neg_email_partage(v_email_hektor) then null else v_email_hektor end))
                      from app_negociateur_fiche f where f.app_personne_id = r.app_personne_id
                     order by f.present_chez_hektor desc, f.derniere_vue desc nulls last limit 1), v_nuit);
            end if;
            -- l'e-mail de l'accès à l'app fait foi ; une autre adresse chez Hektor se signale, une fois
            if v_email_app is not null and v_email_hektor is not null and v_email_hektor <> v_email_app
               and not app_neg_email_partage(v_email_hektor)
               and not exists (select 1 from app_registre_journal jj where jj.objet = 'personne' and jj.objet_id = r.app_personne_id
                                  and jj.evenement = 'ecart' and jj.champ = 'email_pro' and jj.apres = v_email_hektor) then
                insert into app_registre_journal (objet, objet_id, evenement, champ, avant, apres, a_signaler, nuit)
                values ('personne', r.app_personne_id, 'ecart', 'email_pro', v_email_app, v_email_hektor, true, v_nuit);
                v_ecarts_email := v_ecarts_email + 1;
            end if;
        end loop;

        -- le compte rendu
        select jsonb_build_object(
            'a_blanc', p_a_blanc, 'nuit', v_nuit,
            'agences_lues', jsonb_array_length(p_agences), 'agences', (select count(*) from app_registre_agence),
            'agences_nouvelles', v_agences_nouvelles, 'agences_absentes', v_agences_absentes, 'agences_champs', v_agences_champs,
            'alias_crees', v_alias, 'alias', (select count(*) from app_registre_agence_alias),
            'numeros', coalesce((select jsonb_agg(jsonb_build_object('n', g.app_agence_id, 'nom', g.nom, 'hektor', g.hektor_agence_id, 'statut', g.statut)
                                                  order by g.app_agence_id) from app_registre_agence g), '[]'::jsonb),
            'societe_champs', v_societe_champs,
            'societe', (select jsonb_build_object('raison_sociale', s.raison_sociale, 'siret', s.siret, 'carte', s.carte_numero,
                                                  'carte_validite', s.carte_validite) from app_registre_societe s),
            'negos_lus', jsonb_array_length(p_negos), 'personnes', v_personnes, 'personnes_champs', v_personnes_champs,
            'personnes_avec_portable', (select count(*) from app_negociateur_personne where portable is not null),
            'personnes_avec_agence', (select count(*) from app_negociateur_personne where app_agence_id is not null),
            'ecarts_email', v_ecarts_email,
            'evenements', coalesce((select jsonb_object_agg(objet || ':' || evenement, n) from (
                                     select objet, evenement, count(*) n from app_registre_journal where nuit = v_nuit group by 1, 2) e), '{}'::jsonb),
            -- les écritures d'agence des fiches et des biens que les alias ne rattachent pas encore
            'ecritures_non_rattachees', coalesce((select jsonb_agg(jsonb_build_object('ecriture', w.ecriture, 'lignes', w.n) order by w.n desc)
                from (select e.ecriture, count(*) n from (
                          select agence_nom ecriture from app_negociateur_fiche where coalesce(trim(agence_nom), '') <> ''
                          union all select agence_nom from app_dossiers_current where coalesce(trim(agence_nom), '') <> '') e
                       where app_neg_cle_agence(e.ecriture) not in (select cle from app_registre_agence_alias)
                       group by 1 order by 2 desc limit 30) w), '[]'::jsonb),
            'ecarts', coalesce((select jsonb_agg(jsonb_build_object('objet', jj.objet, 'id', jj.objet_id, 'champ', jj.champ,
                                                                    'chez_nous', jj.avant, 'chez_hektor', jj.apres))
                                  from app_registre_journal jj where jj.nuit = v_nuit and jj.evenement = 'ecart'), '[]'::jsonb))
          into v_rapport;
        if p_a_blanc then
            raise exception using errcode = 'P0A01', message = 'a_blanc';
        end if;
    exception when sqlstate 'P0A01' then
        -- à blanc : toutes les écritures du bloc sont annulées, v_rapport reste.
        -- ⚠ MESURÉ À L'ESSAI DU 05/11 : un compteur de numéros N'EST PAS annulé par le retour arrière -- sans cette ligne,
        --   chaque nuit à blanc brûlait 20 numéros (la 1re agence serait née 2000021). On le remet derrière le plus grand
        --   numéro réellement posé (2000001 pour la première).
        perform setval(pg_get_serial_sequence('public.app_registre_agence', 'app_agence_id'),
                       coalesce((select max(app_agence_id) from app_registre_agence), 2000000), true);
    end;
    return v_rapport;
end
