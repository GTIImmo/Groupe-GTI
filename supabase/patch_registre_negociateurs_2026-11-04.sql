create table public.app_negociateur_personne (
    app_personne_id   bigint generated by default as identity (start with 1000001) primary key,
    nom               text not null,
    email             text,
    type_personne     text not null check (type_personne in ('administrateur', 'negociateur', 'secretaire', 'agence', 'inconnu')),
    actif             boolean not null default false,
    origine           text not null,
    app_user_id       uuid,
    a_valider         text,
    cle_regroupement  text not null unique,
    created_at        timestamptz not null default now(),
    updated_at        timestamptz not null default now()
);

create table public.app_negociateur_fiche (
    app_fiche_id          bigint generated by default as identity (start with 1000001) primary key,
    app_personne_id       bigint not null references public.app_negociateur_personne (app_personne_id),
    sorte                 text not null check (sorte in ('fiche_negociateur', 'compte_utilisateur', 'numero_repartition')),
    hektor_negociateur_id text unique,
    hektor_user_id        text,
    hektor_agence_id      text,
    agence_nom            text,
    nom_vu                text,
    email_vu              text,
    telephone             text,
    portable              text,
    user_type             text,
    actif_chez_hektor     boolean not null default false,
    present_chez_hektor   boolean,
    rattache_par          text not null check (rattache_par in ('email', 'nom', 'agence', 'seul', 'decision')),
    premiere_vue          timestamptz not null default now(),
    derniere_vue          timestamptz not null default now(),
    absent_depuis         timestamptz,
    created_at            timestamptz not null default now(),
    updated_at            timestamptz not null default now()
);
create unique index app_negociateur_fiche_user_uniq on public.app_negociateur_fiche (hektor_user_id) where hektor_user_id is not null;
create index app_negociateur_fiche_personne_idx on public.app_negociateur_fiche (app_personne_id);

create table public.app_negociateur_journal (
    id              bigint generated by default as identity primary key,
    app_fiche_id    bigint not null references public.app_negociateur_fiche (app_fiche_id),
    champ           text not null,
    avant           text,
    apres           text,
    vu_le           timestamptz not null default now()
);

-- ── le remplissage, une fois : les fiches de l'annuaire, les comptes sans fiche, les numéros de la répartition sans rien ──
create temp table _src on commit drop as
with annu as (
    select 'fiche_negociateur'::text as sorte, nullif(trim(hektor_negociateur_id), '') as n_id, nullif(trim(hektor_user_id), '') as u_id,
           nullif(trim(hektor_agence_id), '') as agence_id, agence_nom, trim(coalesce(prenom, '') || ' ' || coalesce(nom, '')) as nom_vu,
           nullif(lower(trim(email)), '') as email, telephone, portable, null::text as user_type, coalesce(is_active, false) as actif,
           null::text as force_cle
      from public.app_hektor_negotiator_agency_directory
), comptes as (
    -- les colonnes sont NOMMÉES : sans nom, « select u_id from comptes » lirait le u_id de la requête extérieure
    select 'compte_utilisateur'::text as sorte, null::text as n_id, nullif(trim(id_user), '') as u_id, null::text as agence_id, null::text as agence_nom,
           coalesce(nullif(trim(coalesce(prenom, '') || ' ' || coalesce(nom, '')), ''), display_name) as nom_vu,
           nullif(lower(trim(email)), '') as email, tel as telephone, portable, upper(user_type) as user_type, true as actif,
           null::text as force_cle
      from public.app_user_directory
     where nullif(trim(id_user), '') is not null
       and trim(id_user) not in (select u_id from annu where u_id is not null)
), rep as (
    select trim(hektor_user_id) as u_id, nom_au_moment, count(*) as n
      from public.app_affaire_repartition
     where nullif(trim(hektor_user_id), '') is not null
     group by 1, 2
), rep_seuls as (
    select 'numero_repartition'::text as sorte, null::text as n_id, r.u_id, null::text as agence_id, null::text as agence_nom,
           coalesce((select r2.nom_au_moment from rep r2 where r2.u_id = r.u_id and r2.nom_au_moment !~* 'supprim' order by r2.n desc limit 1),
                    'Utilisateur supprimé n° ' || r.u_id) as nom_vu,
           null::text as email, null::text as telephone, null::text as portable, null::text as user_type, false as actif,
           null::text as force_cle
      from (select distinct u_id from rep) r
     where r.u_id not in (select u_id from annu where u_id is not null)
       and r.u_id not in (select u_id from comptes where u_id is not null)
), admin as (
    -- LE COMPTE ADMINISTRATEUR DE HEKTOR (n° d'utilisateur 4, « GROUPE GTI IMMOBILIER ») : l'API ne le rend JAMAIS (on ne lit
    -- que les comptes SOUS lui, UsersOfParent) ; connu par le journal du worker (« Session Hektor administrateur active »,
    -- user_id 4, rôle ADMIN) et vérifié dans le Chrome de Frédéric le 04/11. Partagé avec le worker.
    -- Rattaché à Frédéric PAR SA DÉCISION (04/11 : « Oui, rattache-le »).
    select 'compte_utilisateur'::text as sorte, null::text as n_id, '4'::text as u_id, null::text as agence_id, null::text as agence_nom,
           'GROUPE GTI IMMOBILIER'::text as nom_vu, null::text as email, null::text as telephone, null::text as portable,
           'ADMIN'::text as user_type, true as actif, 'email:frederic.gerphagnon@gti-immobilier.fr'::text as force_cle
     where not exists (select 1 from public.app_user_directory where trim(id_user) = '4')
       and not exists (select 1 from public.app_hektor_negotiator_agency_directory where trim(hektor_user_id) = '4')
), src as (
    select * from annu union all select * from comptes union all select * from rep_seuls union all select * from admin
), cl as (
    select s.*,
           regexp_replace(trim(coalesce(s.nom_vu, '')), '^\s*(m_mme|mr\.?/mme\.?|mme\.?|mlle\.?|mr\.?|m\.)\s+', '', 'i') as nom_propre,
           case when s.force_cle is not null then 'personne'
                when s.user_type = 'AGENCE' or s.email = 'accueil@gti-immobilier.fr' or s.nom_vu ~* '^\s*groupe\s+gti' or s.nom_vu ~* '^\s*compte\s+formation'
                  -- les fiches génériques sans personne derrière (« gti immobilier » n° 220, « Négo GTI » n° 224)
                  or s.nom_vu ~* '^\s*(gti\s+immobilier|n[ée]go\s+gti)\s*$' then 'agence'
                when s.sorte = 'numero_repartition' and s.nom_vu ~* '^utilisateur supprim' then 'inconnu'
                else 'personne' end as genre,
           -- même clé que cleNom() de lib/pilotage.ts
           lower(regexp_replace(trim(extensions.unaccent(regexp_replace(coalesce(s.nom_vu, ''), '^\s*(m_mme|mr\.?/mme\.?|mme\.?|mlle\.?|mr\.?|m\.)\s+', '', 'i'))), '\s+', ' ', 'g')) as nk
      from src s
), k1 as (
    select cl.*,
           case cl.genre
             -- une agence = une personne par agence (même clé que cleAgence() de lib/pilotage.ts), jamais réunie par l'e-mail
             when 'agence' then 'agence:' || upper(regexp_replace(trim(extensions.unaccent(regexp_replace(
                    coalesce(case when cl.sorte = 'fiche_negociateur' then cl.agence_nom end, cl.nom_vu, ''), '^\s*groupe\s+gti\s*', '', 'i'))), '[\s-]+', '-', 'g'))
             when 'inconnu' then 'inconnu:' || cl.u_id
             else coalesce(cl.force_cle, 'email:' || cl.email, 'nom:' || cl.nk) end as cle1
      from cl
), rep_cle as (
    -- une personne citée sous plusieurs e-mails (gmail et adresse de l'agence) est réunie par son NOM, et marquée à valider
    select nk, (array_agg(cle1 order by (cle1 like 'email:%@gti-immobilier.fr') desc, n desc, cle1))[1] as cle
      from (select nk, cle1, count(*) as n from k1 where genre = 'personne' and force_cle is null group by 1, 2) x
     group by nk
)
select k1.*,
       case when k1.force_cle is not null then k1.force_cle when k1.genre = 'personne' then coalesce(rc.cle, k1.cle1) else k1.cle1 end as cle,
       (k1.force_cle is null and k1.genre = 'personne' and rc.cle is not null and rc.cle <> k1.cle1) as fusion_nom,
       -- les 33 fiches que la DERNIÈRE liste de Hektor (04/11 03:55) ne contient plus : mesuré dans raw_api_response
       case when k1.sorte = 'fiche_negociateur' then k1.n_id <> all (array['16','21','42','24','19','20','65','22','89','39','88','60','87','59','11','58','34',
              '64','81','77','61','63','80','53','14','97','37','43','93','198','165','190','179'])
            when k1.sorte = 'compte_utilisateur' then true else false end as present
  from k1 left join rep_cle rc on rc.nk = k1.nk and k1.genre = 'personne';

insert into public.app_negociateur_personne (nom, email, type_personne, actif, origine, a_valider, cle_regroupement)
select (array_agg(case when genre = 'agence' and sorte = 'fiche_negociateur' then coalesce(agence_nom, nom_propre) else nom_propre end
                  order by (genre = 'agence' and user_type = 'AGENCE') desc, (sorte = 'fiche_negociateur') desc, actif desc, n_id))[1],
       case when cle like 'email:%' then substr(cle, 7) end,
       case when bool_or(user_type = 'ADMIN') then 'administrateur'
            when bool_or(genre = 'agence') then 'agence' when bool_or(genre = 'inconnu') then 'inconnu'
            when bool_or(sorte = 'fiche_negociateur') then 'negociateur' when bool_or(user_type = 'SECRETAIRE') then 'secretaire' else 'inconnu' end,
       bool_or(actif and sorte <> 'numero_repartition'),
       string_agg(distinct sorte, ', '),
       nullif(concat_ws(' ; ',
         case when bool_or(fusion_nom) then 'réunie par le nom (plusieurs e-mails)' end,
         case when cle like 'nom:%' then 'sans e-mail, réunie par le nom' end,
         case when bool_or(sorte = 'fiche_negociateur') and bool_or(user_type = 'SECRETAIRE') then 'fiche de négociateur ET compte de secrétaire' end,
         case when bool_or(genre = 'inconnu') then 'utilisateur supprimé chez Hektor' end,
         -- une boîte d'agence (craponne@, gtiimmobilier.ambert@wanadoo.fr…) ou l'adresse d'un compte d'agence : jamais une clé de
         -- rattachement automatique (étape 2), un futur négociateur créé avec elle irait chez la mauvaise personne
         case when cle like 'email:%' and (substr(cle, 7) ~ '^(gtiimmobilier\.|gti\.immobilier@)'
                   or split_part(substr(cle, 7), '@', 1) in ('accueil', 'ambert', 'annonay', 'brioude', 'courpiere', 'craponne', 'dunieres', 'firminy',
                        'issoire', 'lepuy', 'monistrol', 'montbrison', 'stbonnet', 'stdidier', 'stetienne', 'strambert', 'tence', 'yssingeaux', 'veauche')
                   or substr(cle, 7) in (select lower(trim(email)) from public.app_user_directory where upper(user_type) = 'AGENCE'))
              then 'e-mail partagé avec une agence (pas une clé de rattachement)' end), ''),
       cle
  from _src
 group by cle
 -- un ordre FIXE (type, actifs d'abord, nom) : les numéros de l'essai sont ceux de la pose, si les données n'ont pas bougé
 order by 3, 4 desc, 1;

insert into public.app_negociateur_fiche (app_personne_id, sorte, hektor_negociateur_id, hektor_user_id, hektor_agence_id, agence_nom, nom_vu, email_vu,
                                       telephone, portable, user_type, actif_chez_hektor, present_chez_hektor, rattache_par)
select p.app_personne_id, s.sorte, s.n_id, s.u_id, s.agence_id, s.agence_nom, s.nom_vu, s.email, s.telephone, s.portable, s.user_type, s.actif, s.present,
       case when s.force_cle is not null then 'decision' when s.genre = 'agence' then 'agence' when s.genre = 'inconnu' then 'seul' when s.fusion_nom or s.cle like 'nom:%' then 'nom' else 'email' end
  from _src s join public.app_negociateur_personne p on p.cle_regroupement = s.cle
 order by p.app_personne_id, s.sorte, nullif(s.n_id, '')::int nulls last, nullif(s.u_id, '')::int nulls last;

-- le compte de l'app : par l'e-mail d'une FICHE DE NÉGOCIATEUR ; à défaut par le nom (marqué à valider)
with par_email as (
    select u.id, min(f.app_personne_id) as pid, count(distinct f.app_personne_id) as n
      from public.app_user_profile u
      join public.app_negociateur_fiche f on f.sorte = 'fiche_negociateur' and f.email_vu = lower(trim(u.email))
     group by u.id
), par_nom as (
    select u.id, min(p.app_personne_id) as pid, count(*) as n
      from public.app_user_profile u
      join public.app_negociateur_personne p on p.type_personne <> 'agence'
       and lower(regexp_replace(trim(extensions.unaccent(coalesce(nullif(trim(coalesce(u.first_name, '') || ' ' || coalesce(u.last_name, '')), ''), u.display_name, ''))), '\s+', ' ', 'g'))
         = lower(regexp_replace(trim(extensions.unaccent(p.nom)), '\s+', ' ', 'g'))
     where u.id not in (select id from par_email)
     group by u.id
), choix as (
    select id, pid, false as par_le_nom from par_email where n = 1
    union all select id, pid, true from par_nom where n = 1
)
update public.app_negociateur_personne p
   set app_user_id = c.id,
       a_valider = case when c.par_le_nom then nullif(concat_ws(' ; ', p.a_valider, 'compte de l''app relié par le nom'), '') else p.a_valider end
  from choix c
 where p.app_personne_id = c.pid;

