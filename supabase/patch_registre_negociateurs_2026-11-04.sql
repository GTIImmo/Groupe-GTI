-- ── les contrôles : le patch s'arrête (et ANNULE tout) si l'un est faux ──
do $controle$
declare
    v_manque int; v_fiches int; v_rep int; v_orph int;
begin
    select count(*) into v_manque from public.app_hektor_negotiator_agency_directory d
     where not exists (select 1 from public.app_negociateur_fiche f where f.hektor_negociateur_id = trim(d.hektor_negociateur_id));
    if v_manque <> 0 then raise exception 'ARRET : % fiches de l''annuaire absentes du registre', v_manque; end if;
    select count(*) into v_fiches from public.app_negociateur_fiche where sorte = 'fiche_negociateur';
    if v_fiches <> (select count(*) from public.app_hektor_negotiator_agency_directory) then raise exception 'ARRET : % fiches négociateur au registre', v_fiches; end if;
    select count(distinct trim(r.hektor_user_id)) into v_rep from public.app_affaire_repartition r
     where nullif(trim(r.hektor_user_id), '') is not null
       and not exists (select 1 from public.app_negociateur_fiche f where f.hektor_user_id = trim(r.hektor_user_id));
    if v_rep <> 0 then raise exception 'ARRET : % numéros d''utilisateur de la répartition sans place au registre', v_rep; end if;
    select count(*) into v_orph from public.app_negociateur_personne p
     where not exists (select 1 from public.app_negociateur_fiche f where f.app_personne_id = p.app_personne_id);
    if v_orph <> 0 then raise exception 'ARRET : % personnes sans aucune fiche', v_orph; end if;
end
$controle$;
